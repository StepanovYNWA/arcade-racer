export const AI_STEER_RELEASE = 0.025;

/**
 * Упреждение по рысканию, с. Без него дискретный руль — релейный регулятор:
 * полный выворот держится, пока ошибка не перейдёт через ноль, а к этому моменту
 * машина уже набрала угловую скорость и проскакивает мимо. В прототипе такого
 * не случалось, потому что руль там был плавный (err * 2.2) и сам ослабевал
 * у цели; при переводе на клавиши это свойство потерялось, и соперника
 * раскачивало от барьера до барьера.
 *
 * Здесь оно возвращено единственным способом, который оставляет руль дискретным:
 * рулевая ошибка уменьшается на уже набранный доворот, то есть стрелка
 * отпускается заранее — ровно так, как это делает человек.
 */
