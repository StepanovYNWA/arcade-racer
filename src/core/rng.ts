/**
 * Детерминированный ГПСЧ (mulberry32).
 *
 * В прототипе декор трассы (деревья, разброс покрышек) сыпался через Math.random(),
 * поэтому одна и та же трасса каждый раз выглядела иначе. Физика с M2 идёт
 * фиксированным шагом ради детерминизма — расстановка объектов должна быть такой же
 * воспроизводимой, иначе повтор заезда на «той же» трассе им не будет.
 */
export type Rng = () => number;

export function makeRng(seed: number): Rng {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
